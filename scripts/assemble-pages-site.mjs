/**
 * Builds the complete Cloudflare Pages folder for microgrind.app.
 *
 * A direct upload replaces the whole deployment, so the folder must hold everything:
 *   1. deploy/site-root/  files that only exist on the live site (icons, og.png, /_astro/)   — this repo
 *   2. site-static/       the marketing site (npm run build)                                — this repo
 *   3. dist/              the web app export (npm run dist in MicroGrind/appfiles): app/, .well-known/, _redirects, _headers
 *
 * _redirects = site-static rules (retired niche URLs) on top, then the app rules.
 * _headers   = the app export's file (it already carries the auth/confirm Referrer-Policy).
 *
 * Usage, from this repo: node scripts/assemble-pages-site.mjs <app-dist-dir> <out-dir>
 * (publish-site.yml in the MicroGrind repo runs it after exporting the app).
 */
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const REPO_ROOT = path.join(import.meta.dirname, '..');
const MAX_REDIRECT_RULES = 100;
const CONTROL_FILES = new Set(['_redirects', '_headers']);

function ruleLines(text) {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'));
}

/** Site rules first, then app rules, without duplicates. */
export function mergeRedirects(siteText, appText) {
  const seen = new Set();
  const rules = [];
  for (const line of [...ruleLines(siteText), ...ruleLines(appText)]) {
    const source = line.split(/\s+/)[0];
    if (seen.has(source)) continue;
    seen.add(source);
    rules.push(line);
  }
  if (rules.length > MAX_REDIRECT_RULES) {
    throw new Error(`_redirects has ${rules.length} rules; Pages allows about ${MAX_REDIRECT_RULES}.`);
  }
  if (rules.at(-1) !== '/app/* /app/ 200') {
    throw new Error('_redirects must end with the /app/* fallback.');
  }
  return `# Generated by scripts/assemble-pages-site.mjs. Site rules first, then the app export.\n${rules.join('\n')}\n`;
}

function copyEntries(from, to, { skip = new Set() } = {}) {
  for (const entry of readdirSync(from, { withFileTypes: true })) {
    if (skip.has(entry.name)) continue;
    cpSync(path.join(from, entry.name), path.join(to, entry.name), { recursive: true });
  }
}

/** Returns a list of problems; empty means the folder is safe to upload. */
export function checkPagesFolder(out) {
  const must = [
    'index.html',
    'en/index.html',
    'mg.css',
    'mg.js',
    'fonts/geist.woff2',
    'privacidade/index.html',
    'en/privacy/index.html',
    'logo-mark.png',
    'favicon.ico',
    'og.png',
    'app/index.html',
    'app/plans.html',
    'app/sw.js',
    '.well-known/assetlinks.json',
    '_redirects',
    '_headers',
  ];
  const problems = must.filter((rel) => !existsSync(path.join(out, rel))).map((rel) => `missing ${rel}`);
  if (existsSync(path.join(out, '_headers'))) {
    const headers = readFileSync(path.join(out, '_headers'), 'utf8');
    if (!/\/app\/auth\/confirm\*\s*\n\s*Referrer-Policy:\s*no-referrer/i.test(headers)) {
      problems.push('_headers lost Referrer-Policy: no-referrer on /app/auth/confirm*');
    }
  }
  if (existsSync(path.join(out, '.well-known/assetlinks.json'))) {
    if (readFileSync(path.join(out, '.well-known/assetlinks.json'), 'utf8').includes('COLOCA_AQUI')) {
      problems.push('.well-known/assetlinks.json still has the COLOCA_AQUI placeholder');
    }
  }
  if (existsSync(path.join(out, 'index.html'))) {
    const home = readFileSync(path.join(out, 'index.html'), 'utf8');
    if (!home.includes('/mg.css')) problems.push('index.html is not the marketing homepage');
  }
  return problems;
}

export function assemblePagesSite({ repoRoot = REPO_ROOT, dist, out }) {
  const siteRoot = path.join(repoRoot, 'deploy', 'site-root');
  const siteStatic = path.join(repoRoot, 'site-static');
  if (!dist) throw new Error('Pass the app export folder (MicroGrind/appfiles/dist, npm run dist).');
  for (const [label, dir] of [['deploy/site-root', siteRoot], ['site-static', siteStatic], ['dist (npm run dist)', dist]]) {
    if (!existsSync(dir)) throw new Error(`Missing ${label} at ${dir}.`);
  }
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  copyEntries(siteRoot, out, { skip: new Set(['README.md']) });
  copyEntries(siteStatic, out, { skip: new Set([...CONTROL_FILES, '.well-known', 'app']) });
  copyEntries(dist, out, { skip: CONTROL_FILES });

  writeFileSync(
    path.join(out, '_redirects'),
    mergeRedirects(readFileSync(path.join(siteStatic, '_redirects'), 'utf8'), readFileSync(path.join(dist, '_redirects'), 'utf8'))
  );
  cpSync(path.join(dist, '_headers'), path.join(out, '_headers'));

  const problems = checkPagesFolder(out);
  if (problems.length > 0) throw new Error(`Pages folder is not safe to upload:\n  ${problems.join('\n  ')}`);
  return out;
}

function isDirectRun() {
  const entry = process.argv[1];
  return Boolean(entry) && import.meta.url === pathToFileURL(realpathSync(entry)).href;
}

if (isDirectRun()) {
  const [distArg, outArg] = process.argv.slice(2);
  if (!distArg) {
    console.error('Usage: node scripts/assemble-pages-site.mjs <app-dist-dir> [out-dir]');
    process.exit(2);
  }
  const dist = path.resolve(distArg);
  const out = path.resolve(outArg ?? path.join(REPO_ROOT, 'pages-site'));
  try {
    assemblePagesSite({ dist, out });
    console.log(`Pages folder ready: ${out}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
